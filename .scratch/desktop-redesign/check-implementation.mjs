import { chromium, expect } from '@playwright/test';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, baseURL: 'http://127.0.0.1:3009' });
page.setDefaultTimeout(15000);
const errors=[]; page.on('pageerror', e=>{errors.push(e.message); console.log('BROWSER ERROR',e.message);});
await page.goto('/');
await page.getByRole('link',{name:'Sign in with GitHub',exact:true}).click();
await page.getByRole('link',{name:'Authorize Alice'}).click();
await page.locator('.boards-list, #board-heading').first().waitFor();
if (await page.getByRole('button',{name:'Boards ▾'}).isVisible()) await page.getByRole('button',{name:'Boards ▾'}).click();
await page.getByLabel('Board name',{exact:true}).fill('Desktop implementation');
await page.getByRole('button',{name:'Create board',exact:true}).click();
await page.locator('.tl-container').waitFor();
await page.getByRole('button',{name:'Repositories',exact:true}).click();
await page.getByLabel('Search repositories').fill('alice/project');
await page.getByRole('button',{name:/alice\/project/}).first().click();
await page.getByLabel('State',{exact:true}).selectOption('all');
await page.getByRole('button',{name:'Connect repository',exact:true}).click();
await expect(page.locator('.incoming-candidates > li')).toHaveCount(5);
const before=await page.locator('.tl-shapes').getAttribute('style');
await page.getByRole('button',{name:'Add all matching',exact:true}).click();
await expect(page.locator('.workspace-card')).toHaveCount(5);
await expect(page.locator('#incoming-panel')).toBeVisible();
await expect(page.locator('.tl-shapes')).toHaveAttribute('style',before);
await expect(page.locator('.board-save')).toHaveAttribute('data-save-state','saved');
await page.screenshot({path:'.scratch/desktop-redesign/evidence/implementation-light.png'});
console.log({errors,canvas:await page.locator('.board-canvas').boundingBox()});
await page.getByRole('button',{name:'Close Incoming',exact:true}).click();
await page.getByRole('button',{name:'View',exact:true}).click();
await page.getByLabel('Project',{exact:true}).selectOption({label:'Delivery'});
await page.getByLabel('Connections',{exact:true}).selectOption('all');
await expect(page.locator('.related-links path')).not.toHaveCount(0);
await expect(page.locator('.card-project-fields').first()).toContainText('Sprint 12');
await page.getByLabel('Theme',{exact:true}).selectOption('dark');
await page.screenshot({path:'.scratch/desktop-redesign/evidence/implementation-dark.png'});
await browser.close();
