import { expect, test } from '@playwright/test';
import { applicationOrigin, controlProvider, currentSession, providerOrigin, restartApplication, signIn } from './auth-support.js';
import { validateBoard } from '../../src/shared/boards.js';
import { readRepositoryLocator, readSourcePage } from '../../src/shared/sources.js';

test.skip(process.env['E2E_AUTH_MODE'] === 'unconfigured', 'GitHub authorization is required.');

test('find a repository directly, carry it into a board, and reuse it without paging', async ({ page, browser }, info) => {
  await controlProvider(page.request, { reset: true });
  expect((await page.request.post(`${providerOrigin}/__source-stats/reset`)).ok()).toBe(true);
  await signIn(page);
  await page.getByRole('link', { name: 'Sources', exact: true }).click();
  await page.getByLabel('Repository name or URL').fill('alice/project');
  await page.getByLabel('Repository name or URL').press('Enter');
  await expect(page.locator('#source-items-heading')).toHaveText('alice/project');
  await page.screenshot({ path: info.outputPath('sources-light.png'), fullPage: true });
  await page.getByRole('link', { name: 'Choose a board', exact: true }).click();
  await expect(page.getByText('Choose a board for', { exact: false })).toBeVisible();
  await page.getByLabel('Board name', { exact: false }).fill('Repository connection');
  await page.getByRole('button', { name: 'Create board', exact: true }).click();
  await expect(page.getByLabel('Search repositories')).toHaveValue('alice/project');
  await page.getByRole('button', { name: /alice\/project/ }).first().click();
  await page.getByLabel('Theme', { exact: true }).selectOption('dark');
  await page.getByRole('button', { name: 'Connect repository', exact: true }).click();
  await expect(page.locator('.incoming-candidates > li')).toHaveCount(2);
  await expect(page.locator('.board-save')).toHaveAttribute('data-save-state', 'saved');
  await page.locator('.incoming-candidates > li').first().getByRole('button', { name: /^Add to board:/ }).click();
  await expect(page.locator('.board-save')).toHaveAttribute('data-save-state', 'saved');
  await page.reload();
  await page.getByRole('button', { name: /^Incoming \d+$/ }).click();
  await expect(page.locator('.incoming-candidates > li')).toHaveCount(1);
  await expect(page.locator('.incoming-sources > li')).toHaveCount(1);
  await expect(page.locator('.tl-shape')).toHaveCount(1);
  await page.getByRole('button', { name: 'Repositories', exact: true }).click();
  await page.getByRole('button', { name: /alice\/project/ }).first().click();
  await expect(page.getByRole('button', { name: 'Connect repository', exact: true })).toBeDisabled();
  await page.getByLabel('Theme', { exact: true }).selectOption('dark');
  await page.screenshot({ path: info.outputPath('connection-dark.png'), fullPage: true });
  await page.setViewportSize({ width: 320, height: 900 });
  await page.evaluate(() => { document.documentElement.style.fontSize = '200%'; });
  await page.getByRole('button', { name: '← Repositories', exact: true }).click();
  const input = page.getByLabel('Search repositories');
  await input.focus();
  await expect(input).toBeFocused();
  await expect(input).toBeInViewport();
  expect(await input.evaluate((element) => {
    const rect = element.getBoundingClientRect();
    return element.contains(document.elementFromPoint(rect.left + rect.width / 2, rect.top + rect.height / 2));
  })).toBe(true);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('connection-narrow.png') });
  const stats = await (await page.request.get(`${providerOrigin}/__source-stats`)).text();
  expect(stats).toContain('/user/installations');
  const bob = await browser.newContext({ baseURL: applicationOrigin });
  try {
    const other = await bob.newPage(); await signIn(other, 'Bob');
    const session = await currentSession(other.request);
    if (session.status !== 'signed-in') throw new Error('Expected Bob');
    const response = await other.request.get('/api/sources/recent-repositories', { headers: { 'x-csrf-token': session.csrfToken } });
    expect(readSourcePage(await response.json(), readRepositoryLocator).items).not.toContainEqual({ owner: 'alice', name: 'project' });
  } finally { await bob.close(); }
});

test('repository lookup has actionable failure, retries, and durable account-scoped shortcuts', async ({ page }) => {
  await controlProvider(page.request, { reset: true }); await signIn(page);
  await page.goto('/sources');
  await page.getByLabel('Repository name or URL').fill('https://example.invalid/private/project');
  await page.getByRole('button', { name: 'Find repository', exact: true }).click();
  await expect(page.locator('.repository-finder [role="alert"]')).toBeVisible();
  await expect(page.getByLabel('Repository name or URL')).toBeFocused();
  await page.getByLabel('Repository name or URL').fill('https://github.com/alice/project');
  await page.getByRole('button', { name: 'Find repository', exact: true }).click();
  await expect(page.locator('#source-items-heading')).toHaveText('alice/project');
  await restartApplication(page.request, 'original');
  await page.reload();
  await page.getByRole('button', { name: 'Open alice/project', exact: true }).click();
  await expect(page.locator('#source-items-heading')).toHaveText('alice/project');
  const session = await currentSession(page.request);
  if (session.status !== 'signed-in') throw new Error('Expected Alice');
  const response = await page.request.post('/api/boards', { headers: { origin: applicationOrigin, 'x-csrf-token': session.csrfToken }, data: { title: 'Second board' } });
  const board = validateBoard(await response.json());
  await page.goto(`/boards/${board.id}`);
  await page.getByRole('button', { name: 'Repositories', exact: true }).click();
  await page.getByLabel('Search repositories').fill('alice/project');
  await page.getByRole('button', { name: /alice\/project/ }).first().click();
  await page.getByRole('button', { name: 'Connect repository', exact: true }).click();
  await expect(page.locator('.incoming-candidates > li')).toHaveCount(2);
  await page.getByRole('button', { name: 'Repositories', exact: true }).click();
  await controlProvider(page.request, { sourceDenied: true });
  await page.getByLabel('Search repositories').fill('');
  await page.getByLabel('Search repositories').fill('alice/project');
  await expect(page.locator('.repository-connector [role="alert"]')).toBeVisible();
  await expect(page.locator('.repository-results')).not.toContainText('alice/project');
  await page.getByRole('button', { name: /^Incoming/ }).click();
  await expect(page.locator('.incoming-candidates')).not.toContainText('alice private issue');
  await expect(page.locator('.incoming-candidates > li')).toHaveCount(2);
  await controlProvider(page.request, { sourceDenied: false });
  await page.getByRole('button', { name: 'Repositories', exact: true }).click();
  await page.getByRole('button', { name: 'Retry', exact: true }).click();
  await expect(page.locator('.repository-results')).toContainText('alice/project');
  await expect(page.locator('.repository-connector [role="alert"]')).toHaveCount(0);
});
