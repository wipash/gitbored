import { expect, test } from '@playwright/test';
import type { Page } from '@playwright/test';
import { createEmptyBoardDocument, validateBoard } from '../../src/shared/boards.js';
import { applicationOrigin, controlProvider, currentSession, signIn } from './auth-support.js';
import { expectNativePoint } from './board-gestures.js';

test.use({ viewport: { width: 1440, height: 1000 } });
test.skip(process.env['E2E_AUTH_MODE'] === 'unconfigured', 'Requires controlled GitHub authorization.');
async function cardPosition(page: Page, id: string) {
  const session = await currentSession(page.request);
  if (session.status !== 'signed-in') throw new Error('Expected owner');
  const response = await page.request.get(`/api/boards/${id}`, { headers: { 'X-CSRF-Token': session.csrfToken } });
  const board = validateBoard(await response.json());
  const card = Object.values(board.document.snapshot.store).find((record) => record.id === 'shape:keyboard-card');
  if (card?.typeName !== 'shape') throw new Error('Missing persisted card');
  return { x: card.x, y: card.y };
}
test('Cards traversal, native-held arrow release and modifier-changed Comma preserve ordinary canvas input', async ({ page }) => {
  await controlProvider(page.request, { reset: true });
  await signIn(page);
  const session = await currentSession(page.request);
  if (session.status !== 'signed-in') throw new Error('Expected owner');
  const headers = { Origin: applicationOrigin, 'X-CSRF-Token': session.csrfToken };
  const created = await page.request.post('/api/boards', { headers, data: { title: 'Authenticated keyboard boundary' } });
  const board = validateBoard(await created.json());
  const document = createEmptyBoardDocument();
  const card = { id: 'shape:keyboard-card', typeName: 'shape', type: 'item-card', parentId: 'page:page', index: 'a1', x: 100, y: 100, rotation: 0, opacity: 1, isLocked: false, meta: {}, props: { version: 1, referenceId: 'ref-keyboard-fixture', kind: 'issue', w: 320, h: 240 } };
  expect((await page.request.put(`/api/boards/${board.id}`, { headers, data: { expectedRevision: 0, incoming: board.incoming, document: { ...document, snapshot: { ...document.snapshot, store: { ...document.snapshot.store, [card.id]: card } } } } })).ok()).toBe(true);
  await page.goto(`/boards/${board.id}`);
  const summary = page.locator('.workspace-cards summary');
  const selectCard = page.getByRole('button', { name: 'Select card', exact: true });
  const canvas = page.locator('.tl-container');
  await summary.click();
  await selectCard.click();
  await expect(canvas).toBeFocused();
  await summary.focus();
  await page.keyboard.press('Enter');
  await page.keyboard.press('Tab');
  await expect(selectCard).toBeFocused();
  await page.keyboard.press('ArrowDown');
  await page.keyboard.press('ArrowRight');
  expect(await cardPosition(page, board.id)).toEqual({ x: 100, y: 100 });
  await page.keyboard.press('Escape');
  await expect(page.locator('.workspace-cards')).not.toHaveAttribute('open');
  await expect(summary).toBeFocused();
  await page.keyboard.press('Enter');
  await selectCard.click();
  await page.keyboard.down('ArrowRight');
  await summary.focus();
  await page.keyboard.press('Enter');
  await selectCard.focus();
  await page.keyboard.up('ArrowRight');
  await page.keyboard.press('Enter');
  await page.keyboard.press('ArrowDown');
  await expect.poll(() => cardPosition(page, board.id)).toEqual({ x: 101, y: 101 });
  // Start and modifier-repeat Comma on the canvas, then release over Cards.
  const shape = page.locator('[data-shape-id="shape:keyboard-card"]');
  const shapeBox = await shape.boundingBox();
  if (!shapeBox) throw new Error('Missing rendered card');
  const canvasBox = await canvas.boundingBox();
  if (!canvasBox) throw new Error('Missing canvas bounds');
  // Comma begins a real native pointer gesture. Start away from the next drag,
  // otherwise two clicks at one point invoke native double-click/text behavior.
  const origin = { x: canvasBox.x + 20, y: canvasBox.y + canvasBox.height * 0.5 };
  await expectNativePoint(page, origin);
  expect(origin.x).toBeLessThan(shapeBox.x);
  await page.mouse.move(origin.x, origin.y);
  await canvas.focus();
  await page.keyboard.down('Comma');
  await page.keyboard.down('Shift');
  await page.keyboard.down('Comma');
  await summary.focus();
  await page.keyboard.press('Enter');
  await selectCard.focus();
  await page.keyboard.down('Comma');
  await page.keyboard.up('Comma');
  await page.keyboard.up('Shift');
  // Use an ordinary real pointer drag after release; no synthetic editor releases.
  const dragBox = await shape.boundingBox();
  if (!dragBox) throw new Error('Missing post-release card');
  const dragX = dragBox.x + dragBox.width * 0.75;
  const dragY = dragBox.y + dragBox.height * 0.7;
  await expectNativePoint(page, { x: dragX, y: dragY }, 'shape:keyboard-card');
  await expectNativePoint(page, { x: dragX + 32, y: dragY + 24 }, 'shape:keyboard-card');
  await page.mouse.move(dragX, dragY);
  await page.mouse.down();
  await page.mouse.move(dragX + 32, dragY + 24, { steps: 8 });
  await page.mouse.up();
  const zoom = shapeBox.width / 320;
  await expect.poll(async () => (await cardPosition(page, board.id)).x).toBeCloseTo(101 + 32 / zoom, 4);
  await expect.poll(async () => (await cardPosition(page, board.id)).y).toBeCloseTo(101 + 24 / zoom, 4);
  const afterDrag = await shape.boundingBox();
  expect(afterDrag?.x).toBeCloseTo(shapeBox.x + 32, 3);
  expect(afterDrag?.y).toBeCloseTo(shapeBox.y + 24, 3);
  expect(afterDrag?.width).toBeCloseTo(shapeBox.width, 3);
  await expect(page.locator('.tl-shape')).toHaveCount(1);
  await expect(page.locator('.board-save')).toHaveAttribute('data-save-state', 'saved');
  const durable = await cardPosition(page, board.id);
  await page.reload();
  await expect(page.locator('.tl-container')).toBeVisible();
  expect(await cardPosition(page, board.id)).toEqual(durable);
});
